function formatAddress(city: Place["city"], name: string, category: Place["category"]) {
  const official = officialAddressByName[name];
  if (official) return official;
  const suffix: Record<Place["category"], string> = {
    transport: "官方交通枢纽",
    business: "核心商务片区",
    university: "官方校区或研究机构",
    shopping: "核心商业片区",
    attraction: "官方景区或城市地标",
    food: "餐饮门店",
    custom: "地点",
  };
  return `${city} · ${name} · ${suffix[category]}`;
}

